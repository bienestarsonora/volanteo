create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'viewer' check (role in ('admin','viewer')),
  created_at timestamptz not null default now()
);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where user_id = auth.uid() and role = 'admin'
  );
$$;

-- El estado de planeación conserva la estructura de la web app (Jornadas > ejercicios > rutas > equipos).
create table if not exists public.app_state (
  id text primary key default 'main',
  state jsonb not null,
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id)
);

-- Credenciales de brigadistas. El PIN nunca se expone por SELECT al frontend de campo.
create table if not exists public.brigadista_credentials (
  brigadista_id text primary key,
  nombre text not null,
  activo boolean not null default true,
  pin_hash text not null,
  updated_at timestamptz not null default now()
);

-- Estado operativo separado del JSON de planeación para no reescribir toda la jornada con cada GPS/reporte.
create table if not exists public.route_runtime (
  route_id text primary key,
  status text not null default 'pending' check (status in ('pending','live','done')),
  completed_blocks integer not null default 0,
  completed_units numeric not null default 0,
  progress integer not null default 0 check (progress between 0 and 100),
  started_at timestamptz,
  finished_at timestamptz,
  last_position jsonb,
  last_position_at timestamptz,
  last_progress_at timestamptz,
  updated_at timestamptz not null default now()
);

create table if not exists public.route_reports (
  id uuid primary key default gen_random_uuid(),
  route_id text not null,
  brigadista_id text not null,
  reported_by text,
  block_number integer not null,
  lat double precision,
  lng double precision,
  reported_at timestamptz not null default now(),
  unique(route_id, block_number)
);

create table if not exists public.route_locations (
  id bigint generated by default as identity primary key,
  route_id text not null,
  brigadista_id text not null,
  lat double precision not null,
  lng double precision not null,
  accuracy_m double precision,
  recorded_at timestamptz not null default now()
);

create index if not exists route_reports_route_idx on public.route_reports(route_id, reported_at desc);
create index if not exists route_locations_route_idx on public.route_locations(route_id, recorded_at desc);
create index if not exists route_locations_brigadista_idx on public.route_locations(brigadista_id, recorded_at desc);

