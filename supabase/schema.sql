create or replace function public._field_pin_ok(p_brigadista_id text, p_pin text)
returns boolean
language sql
stable
security definer
set search_path = public, extensions
as $$
  select exists (
    select 1
    from public.brigadista_credentials b
    where b.brigadista_id = p_brigadista_id
      and b.activo = true
      and b.pin_hash = extensions.crypt(coalesce(p_pin,''), b.pin_hash)
  );
$$;

create or replace function public._route_assigned_to(p_route_id text, p_brigadista_id text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.app_state s,
         lateral jsonb_array_elements(coalesce(s.state->'journeys','[]'::jsonb)) j,
         lateral jsonb_array_elements(coalesce(j->'exercises','[]'::jsonb)) e,
         lateral jsonb_array_elements(coalesce(e->'routes','[]'::jsonb)) r
    where s.id='main'
      and coalesce((j->>'archived')::boolean,false)=false
      and r->>'id'=p_route_id
      and coalesce(r->'memberIds','[]'::jsonb) ? p_brigadista_id
  );
$$;

create or replace function public._route_goal(p_route_id text)
returns integer
language sql
stable
security definer
set search_path = public
as $$
  select greatest(1, coalesce(
    nullif((r->>'blockCount')::numeric,0),
    nullif((r->>'goal')::numeric,0),
    1
  )::integer)
  from public.app_state s,
       lateral jsonb_array_elements(coalesce(s.state->'journeys','[]'::jsonb)) j,
       lateral jsonb_array_elements(coalesce(j->'exercises','[]'::jsonb)) e,
       lateral jsonb_array_elements(coalesce(e->'routes','[]'::jsonb)) r
  where s.id='main' and r->>'id'=p_route_id
  limit 1;
$$;

