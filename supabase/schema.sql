create or replace function public.admin_sync_brigadistas(p_people jsonb)
returns void
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  p jsonb;
  v_id text;
  v_name text;
  v_active boolean;
  v_pin text;
  v_existing_hash text;
begin
  if not public.is_admin() then raise exception 'No autorizado'; end if;
  if jsonb_typeof(coalesce(p_people,'[]'::jsonb)) <> 'array' then raise exception 'p_people debe ser un arreglo'; end if;

  -- Lo que ya no está en el catálogo queda inactivo, no se elimina: preserva referencias históricas.
  update public.brigadista_credentials set activo=false, updated_at=now() where activo=true;

  for p in select * from jsonb_array_elements(p_people)
  loop
    v_id := p->>'id';
    v_name := p->>'name';
    v_active := coalesce((p->>'active')::boolean,true);
    v_pin := nullif(trim(coalesce(p->>'pin','')),'');
    if v_id is null or v_name is null then continue; end if;

    select pin_hash into v_existing_hash from public.brigadista_credentials where brigadista_id=v_id;
    if v_existing_hash is null then
      if v_pin is null then v_pin := '1234'; end if;
      insert into public.brigadista_credentials(brigadista_id,nombre,activo,pin_hash,updated_at)
      values(v_id,v_name,v_active,extensions.crypt(v_pin,extensions.gen_salt('bf')),now());
    else
      update public.brigadista_credentials
         set nombre=v_name, activo=v_active, updated_at=now(),
             pin_hash=case
               when v_pin is not null and v_existing_hash <> extensions.crypt(v_pin,v_existing_hash)
                 then extensions.crypt(v_pin,extensions.gen_salt('bf'))
               else v_existing_hash
             end
       where brigadista_id=v_id;
    end if;
  end loop;
end;
$$;

